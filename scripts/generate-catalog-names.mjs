// Regenerates lib/catalogNames.generated.ts
//
// The English catalog's chapter and theme names are inconsistent ("Behavior"
// vs "Behaviour" for the same chapter, one English name for two German
// chapters), while every label, the study guide and the filters are keyed by
// the German names. Both catalogs share chapter/theme numbers ("1.1.01
// Kapitel" / "1.1.01 Chapter"), so this maps each number to its German name
// and getAllQuestions() puts English questions under the same names.
//
// Usage: node scripts/generate-catalog-names.mjs > lib/catalogNames.generated.ts

const DE = "https://raw.githubusercontent.com/yowmamasita/driving-theory/main/driving_theory_questions_de.json";

const questions = await (await fetch(DE)).json();
const chapters = new Map();
const themes = new Map();
function add(map, code, name, what) {
  if (!code) throw new Error(`no ${what} code`);
  if (map.has(code) && map.get(code) !== name) throw new Error(`${what} ${code} has two names: ${map.get(code)} / ${name}`);
  map.set(code, name);
}
for (const q of questions) {
  add(chapters, q.chapter_number.match(/\d+\.\d+\.\d+/)?.[0], q.chapter_name, "chapter");
  add(themes, q.theme_number.match(/\d+\.\d+/)?.[0], q.theme_name, "theme");
}
const byCode = (a, b) => a[0].localeCompare(b[0], "en", { numeric: true });
const obj = (map) => [...map].sort(byCode).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");

console.log(`// GENERATED by scripts/generate-catalog-names.mjs - do not edit by hand.
// Catalog chapter/theme number -> canonical (German) name.

export const CHAPTER_NAME_BY_CODE: Record<string, string> = {
${obj(chapters)}
};

export const THEME_NAME_BY_CODE: Record<string, string> = {
${obj(themes)}
};`);
