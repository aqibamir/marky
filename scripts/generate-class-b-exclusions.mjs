// Regenerates lib/classBExclusions.ts
//
// The catalog has no per-license-class tagging, and chapter-level mapping is
// too coarse: chapters Class B genuinely needs (e.g. 2.2.03 Geschwindigkeit)
// also carry the Lkw/Bus variants of the same question, which a car candidate
// is never asked. This flags the Zusatzstoff questions whose *driver* is
// operating a truck/bus/tractor unit, by matching phrasing in BOTH the German
// and English catalogs (they share question ids) and taking the union - so the
// result is identical whichever language the app is showing.
//
// Usage: node scripts/generate-class-b-exclusions.mjs > lib/classBExclusions.ts

const SOURCES = {
  de: "https://raw.githubusercontent.com/yowmamasita/driving-theory/main/driving_theory_questions_de.json",
  en: "https://raw.githubusercontent.com/yowmamasita/driving-theory/main/driving_theory_questions.json",
};

const HV_DE = "(?:Lkw|Lastkraftwagen|Lastzug|Gliederzug|Sattelzug|Sattelkraftfahrzeug|Kraftomnibus|Omnibus|Bus|Zugmaschine)";
const HV_EN = "(?:truck|lorry|bus|coach|articulated\\s+(?:motor\\s+)?vehicle|semitrailer|tractor[- ]trailer|tractor\\s+unit)";

const HEAVY = new RegExp(
  "(?:" +
    // German - you are driving / it is the subject vehicle
    `mit\\s+(?:einem|Ihrem|dem)\\s+(?:"?Tempo-100-)?${HV_DE}` +
    `|Sie\\s+fahren\\b[^.?!]{0,60}?\\b(?:einen|Ihren|den)\\s+(?:"?Tempo-100-)?${HV_DE}` +
    `|(?:wenn|falls)\\s+Sie\\s+einen\\s+${HV_DE}` +
    `|(?:darf|dürfen)\\s+(?:ein|Ihr)\\s+${HV_DE}` +
    "|dürfen\\s+(?:Lkw|Busse|Omnibusse)\\b" +
    "|als\\s+(?:Lkw|Bus|Schulbus|Omnibus)[-\\s]?fahrer" +
    `|Ihr(?:es|em|en|e)?\\s+${HV_DE}` +
    "|Gelegenheitsverkehr|Linienverkehr|Fahrgastbeförderung|Güterbeförderung" +
    "|Kraftomnibus|Fahrgäste|Tageslenkzeit|Lenkzeit|Auflaufbremse" +
    "|über\\s*3[,.]5\\s*t|mehr\\s+als\\s+3[,.]5\\s*t|7[,.]5\\s*t|\\b12\\s*t\\b" +
    // English catalog
    `|driv(?:e|ing)\\s+(?:a|your|the)\\s+(?:speed[- ]limited\\s+)?${HV_EN}` +
    `|driving\\b[^.?!]{0,60}?\\b(?:a|your|the)\\s+${HV_EN}` +
    `|with\\s+(?:a|your|the)\\s+${HV_EN}\\b` +
    `|speed\\s+(?:a|your|the)\\s+${HV_EN}` +
    `|as\\s+a\\s+(?:school\\s*)?${HV_EN}\\s+driver` +
    `|(?:a|the)\\s+${HV_EN}\\s+with\\s+(?:a\\s+)?(?:permissible|gross)` +
    `|your\\s+${HV_EN}\\b` +
    "|occasional\\s+traffic|scheduled\\s+service|passenger\\s+transport|goods\\s+transport" +
    "|commercially|driving\\s+and\\s+rest|daily\\s+driving\\s+time|overrun\\s+brake" +
    "|over\\s*3\\.5\\s*t|more\\s+than\\s*3\\.5\\s*t|exceeding\\s*3\\.5\\s*t|7\\.5\\s*t|\\b12\\s*t\\b" +
  ")",
  "i"
);

const isZusatzstoff = (q) => {
  const m = q.theme_number.match(/(\d+)\.(\d+)\./);
  return m ? Number(m[1]) === 2 : false;
};

// Guard: a question that is explicitly about driving a car (Pkw) is Class B
// material even if a broad term like "Auflaufbremse" matched - unless it also
// names a genuinely heavy vehicle.
const CAR = /\bPkw\b|\b(?:passenger\s+)?car\b/i;
const STRICT_HEAVY =
  /Lkw|Lastkraftwagen|Lastzug|Gliederzug|Sattel|Kraftomnibus|Omnibus|\bBus\b|Zugmaschine|7[,.]5\s*t|über\s*3[,.]5\s*t|truck|lorry|\bcoach\b|tractor|7\.5\s*t|over\s*3\.5\s*t/i;

const isHeavy = (text) =>
  HEAVY.test(text) && !(CAR.test(text) && !STRICT_HEAVY.test(text));

const flagged = new Map();
for (const [lang, url] of Object.entries(SOURCES)) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${lang} failed: ${res.status}`);
  for (const q of await res.json()) {
    if (isZusatzstoff(q) && isHeavy(q.question_text)) {
      if (!flagged.has(q.question_id)) flagged.set(q.question_id, q.question_text);
    }
  }
}

const ids = [...flagged.keys()].sort();
process.stdout.write(`// GENERATED by scripts/generate-class-b-exclusions.mjs - do not edit by hand.
//
// Zusatzstoff questions whose subject vehicle is a truck, bus or tractor unit,
// i.e. material a Klasse B (car) candidate is never examined on. Detected from
// question phrasing across both the German and English catalogs, so the two
// languages exclude exactly the same ${ids.length} questions.
export const CLASS_B_EXCLUDED_QUESTION_IDS = new Set<string>([
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
]);
`);
console.error(`flagged ${ids.length} questions`);
