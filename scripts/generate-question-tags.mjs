// Regenerates lib/questionTags.generated.ts
//
// Cross-cutting topic tags for every question, on top of the catalog's own
// theme/chapter classification (which is authoritative and left untouched -
// see CHAPTER_INFO in lib/drivingQuestions.ts for that). These tags exist for
// things that cut ACROSS chapters - e.g. "involves alcohol" or "involves
// children" can each show up inside several different chapters - so a
// chapter filter alone can't isolate them.
//
// Rules were built from actual keyword frequency across the full German
// catalog (see the session notes), not guessed, and are matched against the
// German text only - a question's real-world topic doesn't change with
// display language, so tags are keyed by question_id and apply to both the
// German and English catalogs identically.
//
// Usage: node scripts/generate-question-tags.mjs > lib/questionTags.generated.ts

const SOURCE_URL =
  "https://raw.githubusercontent.com/yowmamasita/driving-theory/main/driving_theory_questions_de.json";

// tag slug -> [regex, label, emoji]
const RULES = [
  ["speed_limits", /Geschwindigkeit|km\/h|Richtgeschwindigkeit/, "Speed Limits", "🚦"],
  ["braking_distance", /Bremsweg|Anhalteweg|Reaktionsweg|Reaktionszeit/, "Braking & Stopping Distance", "🛑"],
  ["following_distance", /Sicherheitsabstand|\bAbstand\b/, "Following Distance", "↔️"],
  ["overtaking", /Überholen|Überholvorgang/, "Overtaking", "🔄"],
  ["right_of_way", /Vorfahrt|Vorrang/, "Right of Way", "🚸"],
  ["traffic_signs", /Verkehrszeichen|Vorschriftzeichen|Richtzeichen|Gefahrzeichen/, "Traffic Signs", "🪧"],
  ["traffic_lights", /Ampel|Lichtzeichen|Wechsellicht/, "Traffic Lights", "🚥"],
  ["intersections", /Kreuzung|Einmündung/, "Intersections", "➕"],
  ["parking_stopping", /Parken|Halten\b|Parkscheibe|Parkplatz/, "Parking & Stopping", "🅿️"],
  ["lane_usage", /Fahrstreifen|Fahrspur|Spurwechsel/, "Lane Usage", "🛣️"],
  ["turning_reversing", /Abbiegen|Wenden|Rückwärtsfahren|Rückwärts/, "Turning & Reversing", "↩️"],
  ["roundabout", /Kreisverkehr/, "Roundabouts", "🔁"],
  ["motorway", /Autobahn|Kraftfahrstraße/, "Motorway", "🛤️"],
  ["trailer_towing", /Anhänger|Anhängekupplung|Anhängelast|Stützlast/, "Trailers & Towing", "🚛"],
  ["loading_cargo", /Ladung|Ladegut|Ladungssicherung/, "Loading Cargo", "📦"],
  ["lighting_electrical", /Beleuchtung|Scheinwerfer|Fernlicht|Abblendlicht|Rückstrahler/, "Lighting", "💡"],
  ["tires", /Reifen|Profiltiefe|Reifendruck/, "Tires", "⚙️"],
  ["brakes_technical", /Bremsanlage|Bremsflüssigkeit|Bremspedal|\bABS\b|Feststellbremse/, "Brake Systems", "🔧"],
  ["environment_fuel", /Umweltschutz|Umweltzone|Kraftstoffverbrauch|Emission|Abgas|Feinstaub/, "Environment & Fuel", "🌱"],
  ["documents_license", /Fahrerlaubnis|Führerschein|Fahrzeugpapiere|Zulassung|Versicherungskennzeichen/, "Documents & Licensing", "📋"],
  ["accidents_emergency", /Unfall|Notruf|Rettungsdienst|Erste Hilfe|Verbandkasten|Warndreieck/, "Accidents & Emergencies", "🚑"],
  ["fitness_health", /\bEignung\b|Sehvermögen|Sehschwäche|Krankheit/, "Fitness to Drive", "🩺"],
  ["weather_visibility", /Nebel|Regen|Schnee|Glätte|Glatteis|Dunkelheit|Sichtweite|Aquaplaning|Seitenwind/, "Weather & Visibility", "🌧️"],
  ["children_school", /\bKind\b|Kinder|Schulbus|Schulweg|Spielstraße/, "Children & Schools", "🧒"],
  ["pedestrians", /Fußgänger|Zebrastreifen/, "Pedestrians", "🚶"],
  ["cyclists", /Radfahrer|Fahrrad|Radweg/, "Cyclists", "🚲"],
  ["level_crossing", /Bahnübergang|Andreaskreuz|Bahnschranke/, "Level Crossings", "🚆"],
  ["construction_zone", /Baustelle|Arbeitsstelle/, "Construction Zones", "🚧"],
  ["alcohol_drugs", /Alkohol|Promille|Droge|Medikament/, "Alcohol & Drugs", "🍺"],
  ["fatigue_distraction", /Müdigkeit|Übermüdung|Ablenkung|Sekundenschlaf|Smartphone|Mobiltelefon|Handy/, "Fatigue & Distraction", "😴"],
];

export const TAG_INFO_ENTRIES = RULES.map(([slug, , label, emoji]) => [slug, { label, emoji }]);

const res = await fetch(SOURCE_URL);
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const data = await res.json();

const tagsByQuestion = new Map();
let taggedCount = 0;
for (const q of data) {
  const tags = RULES.filter(([, pat]) => pat.test(q.question_text)).map(([slug]) => slug);
  if (tags.length) {
    tagsByQuestion.set(q.question_id, tags);
    taggedCount++;
  }
}

const entries = [...tagsByQuestion.entries()].sort(([a], [b]) => a.localeCompare(b));

process.stdout.write(`// GENERATED by scripts/generate-question-tags.mjs - do not edit by hand.
//
// Cross-cutting topic tags per question (question_id -> tag slugs), matched
// against the German catalog text and applying identically to both
// languages. Supplements the catalog's own theme/chapter classification for
// topics that cut across chapters (e.g. "involves alcohol"). ${taggedCount} of
// ${data.length} questions have at least one tag; the rest are adequately
// described by their chapter alone.
export const QUESTION_TAGS: Record<string, string[]> = {
${entries.map(([id, tags]) => `  ${JSON.stringify(id)}: [${tags.map((t) => JSON.stringify(t)).join(", ")}],`).join("\n")}
};

export const TAG_INFO: Record<string, { label: string; emoji: string }> = {
${RULES.map(([slug, , label, emoji]) => `  ${JSON.stringify(slug)}: { label: ${JSON.stringify(label)}, emoji: ${JSON.stringify(emoji)} },`).join("\n")}
};
`);
console.error(`tagged ${taggedCount} of ${data.length} questions across ${RULES.length} tags`);
